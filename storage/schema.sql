-- 历史耗时样本表。
-- 表名沿用旧版 gray_scan.db 的 GAMETIME_RECORD，老数据库可以直接复用。
CREATE TABLE IF NOT EXISTS GAMETIME_RECORD (
    KEY_NAME   TEXT NOT NULL,
    P_NUM      REAL NOT NULL,
    CREATED_AT TEXT NOT NULL DEFAULT (datetime('now', 'localtime'))
);

CREATE INDEX IF NOT EXISTS IDX_GAMETIME_KEY ON GAMETIME_RECORD (KEY_NAME);
